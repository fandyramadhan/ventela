/* Renders the JSX section components to a static HTML string and writes it to
   app/_content.js.

   - one-shot:  node gen-static.mjs          (used by `prebuild`)
   - watch:     node gen-static.mjs --watch  (used by `npm run dev`, via dev.mjs)

   In watch mode it re-renders whenever static-entry.jsx or any component it
   imports changes, so editing components/*.jsx updates the page automatically. */
import * as esbuild from 'esbuild';
import { writeFileSync, mkdirSync } from 'fs';

mkdirSync('.gen', { recursive: true });

const WATCH = process.argv.includes('--watch');

const buildOptions = {
  entryPoints: ['static-entry.jsx'],
  bundle: true,
  platform: 'node',
  format: 'esm',
  jsx: 'automatic',
  outfile: '.gen/static.mjs',
  logLevel: 'warning',
  // react-dom/server's bundled CJS uses require('stream') etc.; give it a real require.
  banner: {
    js: "import { createRequire as __cr } from 'module'; const require = __cr(import.meta.url);",
  },
};

// Re-import the freshly built bundle and write the rendered HTML to _content.js.
// The cache-busting query forces a fresh module evaluation on every rebuild.
async function writeContent() {
  const mod = await import('./.gen/static.mjs?t=' + Date.now());
  const html = mod.html;
  writeFileSync(
    'app/_content.js',
    '// AUTO-GENERATED by gen-static.mjs — do not edit by hand.\n' +
      'export default ' +
      JSON.stringify(html) +
      ';\n',
    'utf8'
  );
  console.log('[gen-static] wrote app/_content.js (' + html.length + ' bytes)');
}

if (WATCH) {
  const ctx = await esbuild.context({
    ...buildOptions,
    plugins: [
      {
        name: 'render-content',
        setup(build) {
          build.onEnd(async (result) => {
            if (result.errors.length) return; // keep last good output on error
            await writeContent();
          });
        },
      },
    ],
  });
  await ctx.watch(); // runs an initial build, then rebuilds on change
  console.log('[gen-static] watching components for changes…');
} else {
  await esbuild.build(buildOptions);
  await writeContent();
}
